/* ------------------------------------------------------------------ http */

function corsHeaders(origin, allowed) {
  return {
    // Echo only an origin we actually allow, so a cached response can never
    // hand one site's permission to another. Vary keeps caches honest about
    // this header changing per request.
    'Access-Control-Allow-Origin': allowed ? origin : 'null',
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Max-Age': '86400',
    'Vary': 'Origin',
    'Content-Type': 'application/json',
  };
}

function json(body, status, ctx) {
  return new Response(JSON.stringify(body), {
    status,
    headers: corsHeaders(ctx.origin, ctx.allowed),
  });
}

/* Reads and parses a JSON body, refusing anything oversized before it is
   buffered. Returns null on anything malformed; callers answer 400. */
async function readJson(request) {
  const declared = Number(request.headers.get('content-length') || 0);
  if (declared > BODY_LIMIT) return null;
  try {
    const text = await request.text();
    if (text.length > BODY_LIMIT) return null;
    const parsed = JSON.parse(text);
    return parsed && typeof parsed === 'object' ? parsed : null;
  } catch {
    return null;
  }
}

/* ------------------------------------------------------------ rate limit
 * Best-effort, and deliberately so. State lives in the isolate's memory, so
 * it is per-colo and lost whenever the isolate is recycled -- it will not stop
 * a distributed flood. What it does stop is the realistic case: one script or
 * one stuck page hammering the endpoint and burning a free-tier quota that the
 * whole site depends on. Durable limits would need a KV or Durable Object
 * binding, which cannot be added from the dashboard editor this file targets.
 */
const hits = new Map();   // key -> array of recent timestamps (ms)

function rateLimited(key, limit, windowMs) {
  const now = Date.now();
  const recent = (hits.get(key) || []).filter(ts => now - ts < windowMs);
  recent.push(now);
  hits.set(key, recent);

  // Drop keys that have gone quiet, so a long-lived isolate does not grow
  // a map entry per visitor for ever.
  if (hits.size > 5000) {
    for (const [k, stamps] of hits) {
      if (!stamps.length || now - stamps[stamps.length - 1] > windowMs) hits.delete(k);
    }
  }
  return recent.length > limit;
}

/* --------------------------------------------------------------- contact
 * The contact form has no backend of its own: this route validates a
 * submission and relays it to Web3Forms, which emails it to whichever address
 * WEB3FORMS_KEY was issued for. The key stays server-side, so the published
 * form cannot be scraped and used to send mail by anyone reading the page.
 *
 * To move to a provider that sends from azsco.com itself, replace the fetch
 * below; the validation above it stays as it is.
 */
async function handleContact(request, env, ctx) {
  if (!env.WEB3FORMS_KEY) {
    console.error('WEB3FORMS_KEY is not set');
    return json({ error: 'Contact form unavailable' }, 503, ctx);
  }
  if (rateLimited('contact:' + ctx.ip, 5, 10 * 60 * 1000)) {
    return json({ error: 'Too many requests' }, 429, ctx);
  }

  const form = await readJson(request);
  if (!form) return json({ error: 'Invalid JSON' }, 400, ctx);

  const clean = k => (typeof form[k] === 'string' ? form[k].trim().slice(0, FIELD_LIMIT) : '');

  // Honeypot: a field hidden from people but appealing to bots. Anything in it
  // means a bot, so answer exactly as if it worked and send nothing --
  // reporting the rejection just teaches the bot to try again.
  if (clean('website')) return json({ ok: true }, 200, ctx);

  const name = clean('name');
  const email = clean('email');
  const phone = clean('phone');
  const message = clean('message');
  if (!name || !email || !phone || !message) {
    return json({ error: 'Missing required fields' }, 400, ctx);
  }
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)) {
    return json({ error: 'Invalid email' }, 400, ctx);
  }

  const lang = form.lang === 'ar' ? 'ar' : 'en';
  const service = clean('service');

  try {
    const res = await fetch('https://api.web3forms.com/submit', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify({
        access_key: env.WEB3FORMS_KEY,
        subject: `Website enquiry: ${service || 'General'} — ${name}`,
        from_name: 'AZSCO Website',
        replyto: email,
        // Flat keys: whatever is listed here is what appears in the email.
        Name: name,
        Company: clean('company') || '—',
        Email: email,
        Phone: phone,
        'Inquiry type': service || '—',
        Message: message,
        'Sent from': lang === 'ar' ? 'Arabic site (/ar/)' : 'English site',
      }),
    });

    if (!res.ok) {
      console.error('Web3Forms error', res.status, (await res.text()).slice(0, 500));
      return json({ error: 'Could not send' }, 502, ctx);
    }
    return json({ ok: true }, 200, ctx);
  } catch (err) {
    console.error('Contact relay failure', err);
    return json({ error: 'Could not send' }, 502, ctx);
  }
}

/* ------------------------------------------------------------------ chat */

async function handleChat(request, env, ctx) {
  if (!env.GEMINI_API_KEY) {
    // Configuration problem, not the visitor's fault — do not leak details.
    console.error('GEMINI_API_KEY is not set');
    return json({ error: 'Assistant unavailable' }, 503, ctx);
  }
  if (rateLimited('chat:' + ctx.ip, 12, 60 * 1000)) {
    return json({ error: 'Too many requests' }, 429, ctx);
  }

  const payload = await readJson(request);
  if (!payload) return json({ error: 'Invalid JSON' }, 400, ctx);

  const lang = payload.lang === 'ar' ? 'ar' : 'en';
  const incoming = Array.isArray(payload.messages) ? payload.messages : [];
  if (!incoming.length) return json({ error: 'No messages' }, 400, ctx);

  // Accept only the shape we expect; drop anything else the client sent.
  // Gemini says "model" where the client says "assistant" -- translate the
  // roles and wrap each turn's text in "parts".
  const contents = incoming
    .slice(-MAX_MESSAGES)
    .filter(m => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string')
    .map(m => ({
      role: m.role === 'assistant' ? 'model' : 'user',
      parts: [{ text: m.content.slice(0, MAX_CHARS) }],
    }));

  if (!contents.length) return json({ error: 'No usable messages' }, 400, ctx);

  const model = env.GEMINI_MODEL || DEFAULT_MODEL;
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`;

  try {
    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'x-goog-api-key': env.GEMINI_API_KEY,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        contents,
        systemInstruction: { parts: [{ text: systemPrompt(lang) }] },
        generationConfig: { temperature: 0.3, maxOutputTokens: MAX_TOKENS },
      }),
    });

    if (!res.ok) {
      console.error('Gemini API error', res.status, (await res.text()).slice(0, 500));
      return json({ error: 'Assistant unavailable' }, 502, ctx);
    }

    const data = await res.json();
    const reply = data?.candidates?.[0]?.content?.parts?.map(p => p.text || '').join('').trim();
    if (!reply) return json({ error: 'Empty reply' }, 502, ctx);

    return json({ reply }, 200, ctx);
  } catch (err) {
    console.error('Proxy failure', err);
    return json({ error: 'Assistant unavailable' }, 502, ctx);
  }
}

/* ------------------------------------------------------------------ cms
 * GitHub sign-in for the content editor at /admin/.
 *
 * The editor is a Git-based CMS: it commits product files straight to the
 * repository, so it needs a GitHub token for the person using it. GitHub will
 * not hand one to a static page, because that would mean publishing the OAuth
 * client secret. These two routes are the standard bridge:
 *
 *   /auth      sends the editor to GitHub to approve access
 *   /callback  takes the code GitHub returns, swaps it for a token using the
 *              secret (which stays here), and hands the token to the editor
 *              window through postMessage
 *
 * Secrets, both from an OAuth App created at
 * https://github.com/settings/developers with its callback URL set to this
 * worker's /callback:
 *   GITHUB_OAUTH_CLIENT_ID      plain variable is fine
 *   GITHUB_OAUTH_CLIENT_SECRET  must be a secret
 *
 * Without them both routes answer 503 and the editor simply cannot sign in;
 * nothing else on the worker is affected.
 */
function cmsConfigured(env) {
  return !!(env.GITHUB_OAUTH_CLIENT_ID && env.GITHUB_OAUTH_CLIENT_SECRET);
}

/* The editor window is told the result by postMessage. Only origins on
   ALLOWED_ORIGIN are addressed, so a token can never be posted to a page on
   someone else's domain that happened to open this flow. */
function cmsOrigins(env) {
  return (env.ALLOWED_ORIGIN || '').split(',').map(s => s.trim()).filter(Boolean);
}

function handleCmsAuth(request, env) {
  if (!cmsConfigured(env)) {
    return new Response('Content editor sign-in is not configured.', { status: 503 });
  }
  const url = new URL(request.url);
  const redirect = `${url.origin}/callback`;
  // "repo" is the narrowest scope that still allows committing to a repository
  // that may be private; GitHub has no finer scope for this.
  const target = new URL('https://github.com/login/oauth/authorize');
  target.searchParams.set('client_id', env.GITHUB_OAUTH_CLIENT_ID);
  target.searchParams.set('redirect_uri', redirect);
  target.searchParams.set('scope', 'repo,user');
  return Response.redirect(target.toString(), 302);
}

function cmsResult(status, payload, env) {
  // The editor listens for this exact message shape.
  const message = `authorization:github:${status}:${JSON.stringify(payload)}`;
  const targets = cmsOrigins(env);
  const body = `<!DOCTYPE html><html><head><meta charset="utf-8"><title>Signing in…</title></head>
<body><p>Completing sign-in…</p><script>
(function () {
  var message = ${JSON.stringify(message)};
  var targets = ${JSON.stringify(targets)};
  function send(e) {
    if (!window.opener) return;
    // Answer only the window that started this, and only on an allowed origin.
    if (targets.length && targets.indexOf(e.origin) === -1) return;
    window.opener.postMessage(message, e.origin);
  }
  window.addEventListener('message', send, false);
  if (window.opener) window.opener.postMessage('authorizing:github', '*');
  setTimeout(function () { document.body.innerHTML = '<p>You can close this window.</p>'; }, 1500);
})();
</script></body></html>`;
  return new Response(body, {
    status: status === 'success' ? 200 : 400,
    headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' },
  });
}

async function handleCmsCallback(request, env) {
  if (!cmsConfigured(env)) {
    return new Response('Content editor sign-in is not configured.', { status: 503 });
  }
  const code = new URL(request.url).searchParams.get('code');
  if (!code) return cmsResult('error', { message: 'No code returned by GitHub' }, env);

  try {
    const res = await fetch('https://github.com/login/oauth/access_token', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify({
        client_id: env.GITHUB_OAUTH_CLIENT_ID,
        client_secret: env.GITHUB_OAUTH_CLIENT_SECRET,
        code,
      }),
    });
    const data = await res.json();
    if (!res.ok || !data.access_token) {
      console.error('GitHub token exchange failed', res.status, data && data.error);
      return cmsResult('error', { message: 'GitHub did not return a token' }, env);
    }
    return cmsResult('success', { token: data.access_token, provider: 'github' }, env);
  } catch (err) {
    console.error('CMS auth failure', err);
    return cmsResult('error', { message: 'Sign-in failed' }, env);
  }
}

/* ------------------------------------------------------------- dispatch */

export default {
  async fetch(request, env) {
    const origin = request.headers.get('origin');
    const list = (env.ALLOWED_ORIGIN || '').split(',').map(s => s.trim()).filter(Boolean);
    // Unset means "allow anything", which keeps a fresh deployment working
    // before the variable is configured. Once set, it is enforced here rather
    // than left to the browser: CORS only makes a browser discard a response
    // that this worker has already paid for, and curl ignores it completely.
    const allowed = !list.length || (!!origin && list.includes(origin));
    const ctx = {
      origin: origin || '*',
      allowed,
      ip: request.headers.get('cf-connecting-ip') || 'unknown',
    };

    // The two sign-in routes are ordinary browser navigations, not fetches:
    // they carry no Origin header, so they are handled before the origin check
    // that the chat and contact routes rely on. Neither reads a request body
    // nor touches an API key; the token they return is posted only to an
    // ALLOWED_ORIGIN window.
    const route = new URL(request.url).pathname.replace(/\/+$/, '');
    if (route === '/auth') return handleCmsAuth(request, env);
    if (route === '/callback') return handleCmsCallback(request, env);

    if (request.method === 'OPTIONS') {
      return new Response(null, { status: 204, headers: corsHeaders(ctx.origin, allowed) });
    }
    if (!allowed) {
      console.warn('Blocked origin', origin);
      return json({ error: 'Forbidden' }, 403, ctx);
    }
    if (request.method !== 'POST') {
      return json({ error: 'Method not allowed' }, 405, ctx);
    }

    // /contact takes the contact form; everything else is the chat widget,
    // which has always posted to the worker root.
    const path = new URL(request.url).pathname.replace(/\/+$/, '');
    return path === '/contact'
      ? handleContact(request, env, ctx)
      : handleChat(request, env, ctx);
  },
};
