/**
 * AZSCO — Cloudflare Worker behind the website's assistant and contact form.
 *
 * Routes:
 *   POST /          the chat widget, relayed to the Gemini API
 *   POST /contact   the contact form, relayed to Web3Forms
 *   GET  /auth      GitHub sign-in for the content editor at /admin/
 *   GET  /callback  the other half of that sign-in
 *
 * Self-contained on purpose: no imports, so it can be pasted straight into the
 * Cloudflare dashboard's Worker editor (Workers & Pages -> Create -> Create
 * Worker -> Edit code), with no CLI, build step or paid account. Wrangler works
 * too, for anyone who prefers it:
 *
 *   npx wrangler deploy backend/workers/chat-worker.js --name azsco-chat
 *   npx wrangler secret put GEMINI_API_KEY --name azsco-chat
 *
 * Secrets and variables (Settings -> Variables and Secrets in the dashboard):
 *   GEMINI_API_KEY  secret, required for /   -- free key, no card, from
 *                   https://aistudio.google.com/apikey
 *   WEB3FORMS_KEY   secret, required for /contact -- free key from
 *                   https://web3forms.com; it decides which mailbox enquiries
 *                   land in. Without it the route answers 503 and the form
 *                   tells the visitor to phone instead of silently losing it.
 *   ALLOWED_ORIGIN  plain variable, strongly recommended: comma-separated
 *                   origins, e.g. "https://www.azsco.com,https://azsco.com".
 *                   Requests from anywhere else are refused before either API
 *                   is called. Leave it unset and anyone can point their own
 *                   site at this worker and spend the quota.
 *   GEMINI_MODEL    plain variable, optional; defaults to MODEL below.
 *
 * The prompt block below is generated. Edit CHAT_FACTS / CHAT_RULES in
 * tools/build.py and run `python3 tools/build.py`, which rewrites it here and
 * in backend/api/chat.js, then redeploy. Editing it by hand means the next
 * build silently reverts the change.
 *
 * Why Gemini and not Mistral: Mistral's free tier rate-limits far too
 * aggressively for live visitor traffic (a single test message could exhaust
 * it). Google AI Studio's free tier suits light, ongoing production use --
 * see https://ai.google.dev/gemini-api/docs/models for current limits.
 */

const DEFAULT_MODEL = 'gemini-2.5-flash';

const MAX_CHARS = 1000;     // per chat message
const MAX_MESSAGES = 40;    // per chat request
const MAX_TOKENS = 500;     // per reply
const FIELD_LIMIT = 2000;   // per contact field, after trimming
const BODY_LIMIT = 100_000; // bytes of request body we will read at all

